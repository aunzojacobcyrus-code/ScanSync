@register.simple_tag
def icon(name, size=18, cls=""):
    paths = ICONS.get(name, ICONS["info"])
    return mark_safe(
        f'<svg class="icon {cls}" width="{int(size)}" height="{int(size)}" viewBox="0 0 24 24" fill="none" '
        f'stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" '
        f'aria-hidden="true">{paths}</svg>'
    )


@register.simple_tag
def status_badge(status, label=None):
    if not status:
        return format_html('<span class="badge badge--pending">{}</span>', label or "Not yet scanned")
    key = str(status).lower()
    return format_html('<span class="badge badge--{}"><i class="dot"></i>{}</span>', key, label or str(status).title())


@register.simple_tag
def weekday_chips(days_list):
    """Mon–Sun chips with meeting days highlighted (all highlighted when unrestricted)."""
    from ..models import Weekday

    days = set(days_list or [])
    chips = "".join(
        format_html('<span class="{}">{}</span>', "on" if not days or d.value in days else "", d.label[:2])
        for d in Weekday
    )
    title = "Any day" if not days else ", ".join(d.label for d in Weekday if d.value in days)
    return format_html('<div class="days" title="{}">{}</div>', title, mark_safe(chips))


@register.filter
def pct_of(value, total):
    try:
        return round(int(value) / int(total) * 100) if int(total) else 0
    except (TypeError, ValueError):
        return 0
